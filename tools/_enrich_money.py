"""note収益化playbookを026/027へ、リール撮影+カバー画像を028へ統合。"""
import json, os, io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
PD = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "posts")

def edit(pid, anchor, new_before, guard):
    fp = os.path.join(PD, f"{pid}.json")
    d = json.load(open(fp, encoding="utf-8-sig"))
    b = d["body"]
    if guard in b:
        print(pid, "既存 → skip"); return
    if anchor not in b:
        print(f"[!] {pid} anchor不一致: {anchor[:20]}"); return
    d["body"] = b.replace(anchor, new_before + anchor, 1)
    d["char_count"] = len(d["body"])
    d["notes"] = (d.get("notes") or "") + f" yt-dlp収益化/リール動画(2025)で追加(2026-06-13)。"
    json.dump(d, open(fp, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(pid, "char=", d["char_count"])

