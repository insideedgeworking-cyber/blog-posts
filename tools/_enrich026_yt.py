# -*- coding: utf-8 -*-
"""post_026(Threads)にYouTube抽出のアルゴリズム/バズらせ方/インスタ転用を統合。"""
import json, os, io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
PD = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "posts")
fp = os.path.join(PD, "post_026.json")
d = json.load(open(fp, encoding="utf-8-sig"))
b = d["body"]
chg = []

algo = """## アルゴリズムを上げる（24時間法則・初速・保存）
スレッズで伸ばすには、アルゴリズムが「良い投稿」と判断する条件を押さえます。

- **24時間法則**：スレッズの投稿の寿命は**実質24時間**。投稿時刻から翌日の同時刻までに反応が集中し、24時間を過ぎるとインプレッションが激減します
- **初速30分〜1時間**：投稿直後のいいね・返信・引用・保存・プロフィールクリックが、その後の拡散を大きく左右します
- **エンゲージの優先順位は「保存 ＞ 滞在時間 ＞ いいね」**：いいねは“軽い”評価。後で見返したくなる＝**保存される投稿**が最強。「続きを読む」をクリックさせる滞在時間も重要
- **テキストのみの投稿がいちばん伸びる**：画像・動画をメイン投稿に入れると拡散が抑えられます。**画像は2枚目以降**に置くのがコツ
- **カニバリに注意**：1時間以内に何投稿もすると、自分の投稿同士が食い合って分散します。連投しない
- **投稿のゴールデンタイム**：7:30〜8:30／12〜13時／19〜22時あたり。フォロワーが見ている時間に出して初速を稼ぐ

> 💡 「アルゴリズムが変わった」とよく言われますが、本質は**ユーザー増で閲覧が分散しているだけ**のことも多い。振り回されず、**価値ある投稿を続ける**のが結局いちばん効きます。

"""

baz = """## バズらせ方の手順（リサーチ→真似→改善）
スレッズは**リサーチが9割**。自己流で熱く書くより、伸びている型を真似るほうが圧倒的に早いです。

- **① 同ジャンルで“少フォロワーなのにバズってる投稿”を探す**：フォロワーが多い人が伸びるのは当然。**少フォロワーで伸びている＝投稿そのものが良い**証拠。目安は「いいね100以上＋コメント10以上」。見つけたらスクショで貯める
- **② 共通点を抜き出す**：伸びてる投稿には必ず共通点がある。**(a) よく使われるワード／枕詞**（「ぶっちゃけ」「正直」「断言します」）、**(b) 文章の構成**
- **③ “電車”のように分解して真似る**：例「冒頭ワード→主張→理由→実例」を1両ずつに分け、各両を自分の言葉に置き換える。丸パクリはNG、**要素だけ真似て数字や言い回しを変える**
- **④ 1日に複数投稿してデータを貯める**：自分のバズ投稿の共通点（キラーワード）を見つけ、**同じネタを擦り続けて磨く**。勝ちパターンを数個作って回す

**そのまま効く“バズる型”**
- **実績＋メリット型**：冒頭に「すごい実績＋見るメリット」（例「SNS総フォロワー◯万・月◯万の私が、絶対にやらなかったこと3つ」）
- **コメント誘導型**：最後に問いかけ（例「縦型派？ドラム派？」「みんなの息抜き教えて」）。コメントが増えるほど拡散される
- **感情型**：悔しい・感動したエピソード。応援・共感コメントが集まり盛り上がる

"""

# 挿入: アルゴリズム＋バズらせ方 を「## フォロワーを増やす手順」の前に
a1 = "## フォロワーを増やす手順"
if "24時間法則" in b:
    print("algo 既存 → skip")
elif a1 in b:
    b = b.replace(a1, algo + baz + a1, 1); chg.append("algo+baz")
else:
    print("[!] a1不一致")

# 動線にインスタ転用＆リンク直貼りアフィリを追記
a2 = "## 集客・副業への動線"
insta_repu = """## スレッズ→インスタ転用＆アフィリ（収益化の近道）
- **伸びた投稿はインスタに転用**：スレッズでバズった投稿は“有益と認められた”証拠。1週間ほどあけて微調整し、インスタのリール／フィードにすると**そのまま伸びやすい**。インスタ投稿が大変な人ほど、スレッズで当たりを見つけてから流用すると効率的
- **スレッズは本文にリンクを直接貼れる**（インスタは不可）：アフィリエイトと相性が最強。おすすめ商品の良さ＋リンクをセットで投稿。楽天・Amazonは**セール期（ブラックフライデー・年末年始など）**に合わせると伸びます

"""
if "スレッズ→インスタ転用" in b:
    print("insta転用 既存 → skip")
elif a2 in b:
    b = b.replace(a2, insta_repu + a2, 1); chg.append("insta")
else:
    print("[!] a2不一致")

d["body"] = b; d["char_count"] = len(b)
d["notes"] = (d.get("notes") or "") + " yt-dlpでスレッズ動画(2025)を抽出して増強(2026-06-12):24時間法則/初速/保存>滞在>いいね/テキストのみ最強/カニバリ/リサーチ電車分解/バズる3型/インスタ転用/リンク直貼りアフィリ。"
json.dump(d, open(fp, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
print("post_026 char=", d["char_count"], "| changed:", chg)
