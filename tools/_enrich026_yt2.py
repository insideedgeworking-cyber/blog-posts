# -*- coding: utf-8 -*-
"""post_026(Threads)に深掘り追加: 500文字の基本構成・冒頭1行10パターン・文末?/ツリー投稿・Xリサーチ転用・note高単価。"""
import json, os, io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
PD = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "posts")
fp = os.path.join(PD, "post_026.json")
d = json.load(open(fp, encoding="utf-8-sig"))
b = d["body"]
chg = []

kosei = """## 500文字の“基本構成”と冒頭1行10パターン
スレッズは流し読みが前提。**最初の1行で指を止められるか**が全てです。まず効く基本構成がこちら。

- **冒頭フック**（1行目。極論ぎみでもOK。例「糖質制限を続けると寿命が10年縮みます」）
- **読者の気持ちの代弁**（例「炭水化物を抜くと痩せるけど、正直しんどいですよね」）
- **最悪の未来の提示**（例「このまま続けると体を壊して逆効果に…」）
- **導入＝結論を先出し**（例「結論、糖質は人によって最適量が違います」）→ そこから中身へ

**そのまま使える“冒頭1行”10パターン**
- **① 自己紹介（属性）**：「30歳ママです」「元OLの主婦です」
- **② 数字**：「半年で◯◯を達成した方法」「1日5分で変わる」
- **③ 続きが気になる**：「ご報告です」「ここだけの話なんですけど」
- **④ 専門性**：「保育士10年目の私が」「年間300人面接して分かったこと」
- **⑤ 限定公開**：「今夜で消します」「期間限定で公開中」
- **⑥ 逆張り**：「貯金はしてはダメ」「ダイエットはしない方が痩せる」
- **⑦ 面白悪口・自虐**：「旦那の愚痴いいですか？」（攻撃的・属性叩きはNG）
- **⑧ トレンド・季節**：「クリスマス前に押さえたい◯◯」
- **⑨ あるある系**：「育児あるある」「職場あるある」（共感→フォローされやすい）
- **⑩ 緊急性・断言**：「断言します。知らないとやばい」

投稿後は**チェック**を：同じ語尾が3回続いてないか／主語と述語がねじれてないか／冗長表現はないか／毎回同じ言い回しになっていないか／冒頭が上の10パターンのどれかになっているか。

## 滞在時間を伸ばす2つの小ワザ
- **文末を「？」で終える**：コメントが増える → コメント欄の会話が気になって他の人の滞在時間も伸びる → さらに拡散。ただし**コメントにDMでプレゼント等のインセンティブを付けるのは規約違反**。「あなたの悩みを教えて」程度の自然な問いかけに
- **ツリー投稿（自分の返信欄に続きを書く）**：1投稿で収まらない時は続きを下に。**続きが気になる形で1個目を終える**と「続きを読む」が押され、滞在時間が伸びます

"""

a1 = "## フォロワーを増やす手順"
if "冒頭1行10パターン" in b:
    print("構成/10パターン 既存 → skip")
elif a1 in b:
    b = b.replace(a1, kosei + a1, 1); chg.append("kosei")
else:
    print("[!] a1不一致")

# Xリサーチ転用＋note高単価マネタイズ を「## スレッズ→インスタ転用」の後ろ…ではなく動線の前に追加
xresearch = """## さらに効く2つの裏ワザ（Xリサーチ／note高単価）
- **Xで伸びてる投稿をスレッズに“輸入”する**：Xで一般の人がバズらせている投稿を探し、スレッズにまだ無ければチャンス。**材料を集めて自分の視点で編集**して投稿すると伸びやすい（丸パクリはNG）
- **収益はアフィリだけでなく“note高単価”も**：PR表記の規制でアフィリがやりにくくなった今、**スレッズの文章 → noteへ誘導**して、サブスク（月額）や1本数千〜2万円の有料記事を売る形が伸びています。文章で集めた“文字を読む層”は説得力を受け取りやすく、商品が売れやすいのが強みです

"""
a2 = "## 集客・副業への動線"
if "Xで伸びてる投稿をスレッズに" in b:
    print("Xリサーチ/note 既存 → skip")
elif a2 in b:
    b = b.replace(a2, xresearch + a2, 1); chg.append("xresearch")
else:
    print("[!] a2不一致")

d["body"] = b; d["char_count"] = len(b)
d["notes"] = (d.get("notes") or "") + " yt-dlpスレッズ動画(2025)で深掘り追加(2026-06-13):500字基本構成・冒頭1行10パターン・文末?/ツリー投稿・チェックリスト・Xリサーチ輸入・note高単価マネタイズ。"
json.dump(d, open(fp, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
print("post_026 char=", d["char_count"], "| changed:", chg)
