# -*- coding: utf-8 -*-
"""post_028にリール台本のAI分析法・フォロー即決化・やめた方がいい(ストーリー枚数/HDR/別垢BAN連鎖)を追加。"""
import json, os, io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
PD = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "posts")
fp = os.path.join(PD, "post_028.json")
d = json.load(open(fp, encoding="utf-8-sig"))
b = d["body"]
chg = []

# ① リールの型をAIで分析する手順
analyze = """## 伸びるリールは“型をAIで分析”して作る
2025年は、フォローまでの流れが**「リールを見る → そのまま即フォロー」**に変わりました（昔のように一度プロフィールを見てから、ではない）。だから**リール1本の中身＝台本がすべて**。そして伸びる台本には“当たる型”があります。0から自分で考えず、**伸びてる型をAIで分析して使う**のが最短です。

- **① 伸びてるリールを見つける**（虫めがね→ジャンルのキーワードで検索）
- **② そのリールを文字起こし**：動画をダウンロード（SnapInsta等）→ **Notta（ノッタ）** などで文字起こし
- **③ ChatGPTに分析させる**：「以下のリール台本の構成を、他ジャンルでも使えるように分析して書き出して」と指示＋台本を貼る → **再現できる“型”が抽出**できる
- **④ その型に自分のネタを当てはめる**（クッキーの型と同じ。丸パクリはNG、構成だけ借りる）

料理を始める初心者が、いきなり自己流より**レシピ通り**に作るほうが上手いのと同じです。

"""
a1 = "## そのまま使える投稿の“型”（例文つき）"
if "伸びるリールは“型をAIで分析”" in b:
    print("リール分析 既存 → skip")
elif a1 in b:
    b = b.replace(a1, analyze + a1, 1); chg.append("analyze")
else:
    print("[!] a1不一致")

# ② 注意点に「やめた方がいい」3点を追記
yamero = """## やめた方がいいこと（2025年版・最新）
昔は正解でも、今は逆効果になっていることがあります。

- **ストーリーを一度に大量（10枚以上）に出さない**：上の「…」が長いと全部見られず、逆に反応が落ちます。**1回3〜5枚**まで（毎日出すのはOK、量を盛りすぎない）
- **毎日投稿にこだわりすぎない**：質を落としてまで毎日出すより、**週3回ほどでクオリティを優先**（2日に1本でも十分伸びます）
- **撮影のHDR機能はオフ**に：眩しくなったり色が不自然になりがち。色は撮影後の編集で調整
- **“本アカウント（本垢）”の規約違反に注意**：同じスマホに入っているアカウントは、1つが規約違反で停止されると**連鎖して全部停止**されることがあります。カフェのBGMが入った動画・他人の投稿のスクショ転載などは、副業用でない普段のアカウントでもやらないこと

"""
a2 = "## よくある質問（FAQ）"
if "やめた方がいいこと（2025年版" in b:
    print("やめた方 既存 → skip")
elif a2 in b:
    b = b.replace(a2, yamero + a2, 1); chg.append("yamero")
else:
    print("[!] a2不一致")

d["body"] = b; d["char_count"] = len(b)
d["notes"] = (d.get("notes") or "") + " yt-dlpリール/プロフ動画(2025)で追加(2026-06-13):フォロー即決化・リール台本のAI分析(Notta→ChatGPT)・やめた方がいい(ストーリー3-5枚/週3投稿/HDRオフ/別垢規約違反でBAN連鎖)。"
json.dump(d, open(fp, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
print("post_028 char=", d["char_count"], "| changed:", chg)
