"""post_013(ブログの始め方/how-to)・post_012(ブログ挑戦/体験談)を本文化。誠実路線・相互リンク。"""
import json, os, io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
PD = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "posts")

def save(pid, title, category, keywords, body, excerpt, notes):
    fp=os.path.join(PD,f"{pid}.json"); d=json.load(open(fp,encoding="utf-8-sig"))
    d["title"]=title; d["category"]=category; d["keywords"]=keywords
    d["body"]=body; d["char_count"]=len(body); d["excerpt"]=excerpt
    d["status"]="drafting"; d["notes"]=(d.get("notes") or "")+notes
    json.dump(d,open(fp,"w",encoding="utf-8"),ensure_ascii=False,indent=2)
    print(f"{pid} 本文化 char={d['char_count']} : {title}")

