# ===== Instagram (post_028) =====
jobs["post_028"] = {
    "first_h2": "## インスタが副業に強い理由（データで見る）",
    "switch": switch_section("この記事は**Instagram**の伸ばし方です。"),
    "before_matome": """## そのまま使える投稿の“型”（リール構成つき）
インスタは**リールで発見→保存される投稿で信頼→ストーリーでファン化**。具体テンプレで動きましょう。

- **リールの構成テンプレ**：①最初の2秒で結論/フック（例「未経験がインスタでやりがちな失敗3つ」）→②本編をテンポよく3点→③最後に「保存して見返してね／プロフfrom詳細」
- **“保存される”投稿の型**：「○○のやり方まとめ」「初心者が陥る失敗」「使えるツール5選」など、後で見返したくなる中身
- **ストーリーのネタ**：質問スタンプ・アンケート・今日の作業・舞台裏。毎日出して交流する
- **ハイライト設計**：自己紹介／実績／人気投稿／リンク導線、の4枠を固定で置く

**型を活かすコツ**
- **ハッシュタグは大・中・小を混ぜて10〜15個**：ビッグタグだけだと埋もれます
- **投稿頻度の目安**：リール週3〜5本＋ストーリー毎日。続けるほど“発見”に乗りやすい
- **ジャンルとプロフィールの世界観をそろえる**（雑多はNG）

## よくある質問（FAQ）
- **フォロワー0でも伸びる？** … リールはフォロー外の「発見」に乗るので、0からでも拡散します。2025年の改定でフォロワー数に左右されにくくなりました
- **顔出しは必要？** … 不要。AIの4コマ漫画や図解、手元動画など顔出しなしで伸ばす人も多いです
- **何を投稿すればいい？** … まずジャンルを1つに決め、上のリール構成と“保存される型”から。料理系はAI画像が不自然になりがちなので注意
- **どれくらいで成果が出る？** … 個人差は大きいですが、リールを継続して数か月が目安。派手な「月◯百万」は上澄みなので焦らない
- **収益化は何から？** … 初心者はアフィリエイトから。プロフィールのリンクとストーリーで誘導します

""",
}

for pid, j in jobs.items():
    fp = os.path.join(PD, f"{pid}.json")
    d = json.load(open(fp, encoding="utf-8-sig"))
    b = d["body"]
    if "どれから始める？（使い分け）" in b:
        print(pid, "既に追加済 → skip"); continue
    # ① 使い分けを最初のH2の前に
    if j["first_h2"] not in b:
        print(f"[!] {pid} first_h2不一致 → skip"); continue
    b = b.replace(j["first_h2"], j["switch"] + j["first_h2"], 1)
    # ② 型＋FAQ を ## まとめ の前に
    if "## まとめ" not in b:
        print(f"[!] {pid} まとめ不一致 → skip"); continue
    b = b.replace("## まとめ", j["before_matome"] + "## まとめ", 1)
    d["body"] = b; d["char_count"] = len(b)
    json.dump(d, open(fp, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"{pid} 更新 char={d['char_count']}")
print("done")
