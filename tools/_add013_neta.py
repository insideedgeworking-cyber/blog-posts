import json, os, io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
PD = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "posts")
fp = os.path.join(PD, "post_013.json")
d = json.load(open(fp, encoding="utf-8-sig"))
b = d["body"]
chg = []

def ins(anchor, text, guard):
    global b
    if guard in b: print("skip(既存):",guard); return
    if anchor in b: b = b.replace(anchor, text+anchor, 1); chg.append(guard)
    else: print("[!] anchor不一致:",anchor[:24])

# ① サーバー・ドメイン・テーマの選び方
sec1 = """## サーバー・ドメイン・テーマの選び方（迷わない基準）
「どれを選べばいいの？」で止まりがちなので、最低限の基準だけ。

- **レンタルサーバー**：初心者は**“表示速度・サポート・クイックスタート対応”**で選べばOK。エックスサーバーやConoHa WINGなどの定番なら失敗しません。月1,000円前後
- **独自ドメイン**：迷ったら**「.com」**でOK（いちばん一般的）。サーバーとセット契約で無料になることも。名前は短く・サイト内容に関係するものを
- **WordPressテーマ**：見た目と機能のテンプレート。**最初は無料の「Cocoon」で十分**。本格的にやるなら有料テーマ（SWELL・AFFINGER・JIN など）が作業効率と装飾で有利。後から変更もできるので、迷うなら無料スタートでOK

"""
ins("## WordPressブログの始め方【7ステップ】", sec1, "サーバー・ドメイン・テーマの選び方")

# ② 特化 vs 雑記
sec2 = """## ブログは“特化”と“雑記”どっち？（ジャンルの決め方）
最初に迷うのがジャンル。ざっくりこう違います。

- **特化ブログ**（1テーマに絞る）：専門性が出て**稼ぎやすい・SEOに強い**。ただしネタ切れしやすい
- **雑記ブログ**（何でも書く）：書きやすく続けやすいが、**専門性が薄く伸びにくい**

初心者におすすめは、その中間の**「ゆる特化」（2〜3個の関連ジャンルに絞る）**。例：副業×AI×ブログ運営、のように。そして——**自分より詳しい人がいても書いて大丈夫**です。読者は“同じ目線で、実体験を語ってくれる人”の記事を求めています。完璧な専門家である必要はありません。

"""
ins("## 最初の記事の書き方", sec2, "“特化”と“雑記”どっち")

# ③ セルフバックで最初の収益
sec3 = """## まず“セルフバック”で最初の収益を作る
「アクセスゼロなのに、いきなり稼げるわけない…」——そんな初心者の最初の一歩に効くのが**セルフバック（自己アフィリエイト）**です。

ASPに登録すると、**自分でクレジットカードを作る・口座を開設する・無料登録する**などで報酬がもらえる案件があります。これを使えば、**アクセスが無くても最初の数千〜数万円を実際に手にできる**んです。

メリットは2つ。**①アフィリの仕組みを“体験”として理解できる**こと、**②最初の収益でモチベーションが続く**こと。「1円も稼げない」で挫折しがちな最初の壁を、ここで越えられます（※同じ案件は1回限りが基本。乱用はしない）。

"""
ins("## いくら稼げる？（正直に）", sec3, "“セルフバック”で最初の収益")

# ④ オワコン論
sec4 = """## 「ブログはオワコン・稼げない」って本当？
始める前に必ず目にする「ブログはもうオワコン」「稼げない」という声。正直に答えます。

**結論、オワコンではないけれど、楽でもありません。** AIで参入する人が増えて、薄い記事は淘汰されるようになりました。でも逆に言えば、**“自分の体験・独自の切り口”を乗せた記事は、むしろ目立ちやすくなった**とも言えます。

「稼げない」と言う人の多くは、**数か月でやめた人**です。ブログは立ち上がりが遅いだけで、続けて改善した人は今もちゃんと伸びています。**楽に大金は無理。でも、続けた人が資産を持てる**——これがブログの正直なところです。

"""
ins("## まとめ", sec4, "オワコン・稼げない")

d["body"]=b; d["char_count"]=len(b)
